# Function to create commits
create_commit() {
    local date=$1
    local message=$2
    local hour=$((14 + RANDOM % 8))
    local minute=$((RANDOM % 60))
    local datetime="$date $(printf "%02d:%02d:00" $hour $minute)"
    
    echo "$date: $message" >> .commit_history
    git add .commit_history 2>/dev/null || git add README.md
    
    GIT_AUTHOR_DATE="$datetime" GIT_COMMITTER_DATE="$datetime" git commit -m "$message" --quiet
    echo "  ✓ $date - $message"
}

